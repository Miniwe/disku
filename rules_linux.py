"""Knowledge base for Linux: which paths are junk, which are precious.

Every rule says three things: how safe removal is, what the thing actually is,
and the *native* way to reclaim it -- `apt-get clean`, `journalctl --vacuum`,
`docker system prune` always beat `rm -rf`, because they leave the tool that
owns the bytes with a consistent view of them afterwards.

Paths are matched relative to whichever user's home they sit in (so a rule
written `.cache/pip` covers /home/ubuntu, /home/deploy and /root alike), or
absolute when the pattern starts with `/`. See rules.py for the matcher.

The scanner never deletes anything -- these are report annotations.
"""

